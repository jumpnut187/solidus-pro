from __future__ import annotations

import sys
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

REPO = Path(__file__).resolve().parents[2]
ROOT_FILE = REPO / "requirements-ci.txt"
OUT_FILE = REPO / "constraints-ci.txt"

CI_MARKER_ENV = {
    "python_version": "3.13",
    "python_full_version": "3.13.0",
    "sys_platform": "linux",
    "platform_system": "Linux",
    "platform_machine": "x86_64",
    "os_name": "posix",
    "implementation_name": "cpython",
    "platform_python_implementation": "CPython",
    "extra": "",
}

def read_requirements(path: Path) -> list[Requirement]:
    reqs: list[Requirement] = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-r "):
            reqs.extend(read_requirements(path.parent / line[3:].strip()))
        elif line.startswith("-"):
            raise SystemExit(f"{path.name}: unsupported option line: {raw!r}")
        else:
            reqs.append(Requirement(line))
    return reqs

def applies(req: Requirement) -> bool:
    return req.marker is None or req.marker.evaluate(CI_MARKER_ENV)

def main() -> int:
    pins: dict[str, str] = {}
    missing: list[str] = []
    stack = [(req, "requirements-ci.txt") for req in read_requirements(ROOT_FILE)]
    while stack:
        req, parent = stack.pop()
        if not applies(req):
            continue
        name = canonicalize_name(req.name)
        if name in pins:
            continue
        try:
            dist = distribution(req.name)
        except PackageNotFoundError:
            missing.append(f"{name} (required by {parent})")
            continue
        pins[name] = dist.version
        for spec in dist.requires or []:
            stack.append((Requirement(spec), name))

    if missing:
        print("Not installed in this environment:", file=sys.stderr)
        for item in sorted(missing):
            print(f"  {item}", file=sys.stderr)
        print("Install them first, then rerun.", file=sys.stderr)
        return 1

    header = (
        "# Generated by scripts/ci/update_constraints.py -- do not edit by hand.\n"
        "# Pins the full dependency closure of requirements-ci.txt to the\n"
        "# versions in the development venv, evaluated for Linux x86_64 /\n"
        "# CPython 3.13.\n"
    )
    body = "".join(f"{name}=={pins[name]}\n" for name in sorted(pins))
    OUT_FILE.write_text(header + body)
    print(f"Wrote {len(pins)} pins to {OUT_FILE.relative_to(REPO)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
